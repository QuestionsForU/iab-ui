import { applyGeneratedDefaults, buildNewRecordDefaults, nextPaddedCode } from "./recordNumbers";

describe("record numbers", () => {
    it("pads the next code after the highest matching value", () => {
        expect(nextPaddedCode([
            { visitId: "VIS00013" },
            { visitId: "VIS00002" },
            { visitId: "OTHER" },
        ], "visitId", "VIS", 5)).toBe("VIS00014");
    });

    it("generates a visit id for a new patient and replaces a previous generated value", () => {
        const first = applyGeneratedDefaults({}, buildNewRecordDefaults("patient", []));
        const second = applyGeneratedDefaults(first, buildNewRecordDefaults("patient", [{ visitId: "VIS00020", mrNo: "MR00020", patientNo: "PAT00020" }]));

        expect(first.visitId).toBe("VIS00001");
        expect(second.visitId).toBe("VIS00021");
        expect(second.mrNo).toBe("MR00021");
    });

    it("keeps a visit id that was not generated by the form", () => {
        const current = applyGeneratedDefaults({ visitId: "VIS-MANUAL" }, buildNewRecordDefaults("patient", []));
        expect(current.visitId).toBe("VIS-MANUAL");
    });

    it("generates the next equipment access key", () => {
        expect(buildNewRecordDefaults("equipment", []).accessKey).toBe("AK00000001");
        expect(buildNewRecordDefaults("equipment", [{ accessKey: "AK00000007" }]).accessKey).toBe("AK00000008");
        expect(buildNewRecordDefaults("equipment", []).isActive).toBe("Yes");
    });

    it("defaults a test rate to standard pricing for one year", () => {
        const defaults = buildNewRecordDefaults("testRate", [], new Date("2026-10-25T12:00:00Z"));
        expect(defaults.rateType).toBe("Standard");
        expect(defaults.effectiveFrom).toBe("2026-10-25");
        expect(defaults.effectiveTo).toBe("2027-10-25");
        expect(defaults.isActive).toBe("Yes");
    });
});
